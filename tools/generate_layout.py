"""Generate a fixed union matrix and default bindings from the recovered Vial data."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "boards/arm/tofu65_3_0"


def generate():
    definition = json.loads((ROOT / "analysis/vial-definition.json").read_text())
    positions = []
    with (ROOT / "analysis/ansi-matrix.csv").open(newline="") as stream:
        for row in csv.DictReader(stream):
            positions.append((int(row["matrix_row"]), int(row["matrix_col"]), row["label"]))
    positions += [(6, 2, "SPLIT_BACKSPACE_EXTRA"), (1, 4, "SPLIT_LSHIFT_EXTRA")]
    union = set()
    for row in definition["layouts"]["keymap"]:
        for item in row:
            if isinstance(item, str):
                union.add(tuple(map(int, item.split("\n")[0].split(","))))
    if {(r, c) for r, c, _ in positions} != union or len(positions) != 69:
        raise ValueError("Recovered layout union differs from expected 69 positions")
    matrix = ["/* Generated by tools/generate_layout.py. All stock switch positions. */",
              "/ {", "    tofu_transform: matrix_transform {",
              '        compatible = "zmk,matrix-transform";',
              "        rows = <14>;", "        columns = <8>;", "        map = <"]
    for r, c, label in positions:
        matrix.append(f"            RC({r},{c}) /* {label} */")
    matrix += ["        >;", "    };", "};"]
    (BOARD / "tofu65_3_0-matrix.dtsi").write_text("\n".join(matrix) + "\n")

    aliases = {"MINUS": "MINUS", "EQUAL": "EQUAL", "BACKSPACE": "BSPC",
               "DELETE": "DEL", "LBRACKET": "LBKT", "RBRACKET": "RBKT",
               "BACKSLASH": "BSLH", "CAPS": "CAPS", "SEMICOLON": "SEMI",
               "APOSTROPHE": "SQT", "ENTER": "RET", "LSHIFT": "LSHFT",
               "RSHIFT": "RSHFT", "LCTRL": "LCTRL", "LGUI": "LGUI",
               "LALT": "LALT", "RALT": "RALT", "RGUI": "RGUI",
               "COMMA": "COMMA", "DOT": "DOT", "SLASH": "FSLH"}
    options = ["TOFU_SPLIT_BACKSPACE", "TOFU_ISO_ENTER", "TOFU_SPLIT_LSHIFT", "TOFU_SPACE_7U"]
    out = ["/* Generated. Edit config/layout-options.h or a personal keymap. */",
           "#include <behaviors.dtsi>", "#include <dt-bindings/zmk/keys.h>"]
    for option in options:
        out += [f"#ifndef {option}", f"#define {option} 0", "#endif",
                f"#if {option} != 0 && {option} != 1", f'#error "{option} must be 0 or 1"', "#endif"]
    out += ["#if TOFU_ISO_ENTER", "#define TOFU_ENTER_POSITION &kp NUHS",
            "#define TOFU_BACKSLASH_POSITION &kp RET", "#else",
            "#define TOFU_ENTER_POSITION &kp RET", "#define TOFU_BACKSLASH_POSITION &kp BSLH", "#endif",
            "#if TOFU_SPLIT_BACKSPACE", "#define TOFU_EXTRA_BACKSPACE &kp DEL", "#else",
            "#define TOFU_EXTRA_BACKSPACE &none", "#endif",
            "#if TOFU_SPLIT_LSHIFT", "#define TOFU_EXTRA_SHIFT &kp NUBS", "#else",
            "#define TOFU_EXTRA_SHIFT &none", "#endif",
            "#if TOFU_SPACE_7U", "#define TOFU_RIGHT_ALT &none", "#else",
            "#define TOFU_RIGHT_ALT &kp RALT", "#endif", "",
            "/ {", "    behaviors {", "        uf2_boot: unicore_bootloader {",
            '            compatible = "kbdfans,unicore-bootloader";',
            '            label = "UNICORE_BOOTLOADER";', "            #binding-cells = <0>;",
            "        };", "    };", "    keymap {", '        compatible = "zmk,keymap";',
            "        base {", "            bindings = <"]
    special = {"BACKSLASH": "TOFU_BACKSLASH_POSITION", "ENTER": "TOFU_ENTER_POSITION",
               "RALT": "TOFU_RIGHT_ALT", "RGUI": "&mo 1",
               "SPLIT_BACKSPACE_EXTRA": "TOFU_EXTRA_BACKSPACE", "SPLIT_LSHIFT_EXTRA": "TOFU_EXTRA_SHIFT"}
    for r, c, label in positions:
        code = "N" + label if label.isdigit() else aliases.get(label, label)
        out.append(f"                {special.get(label, '&kp ' + code)} /* {r},{c}: {label} */")
    out += ["            >;", "        };", "        function {", "            bindings = <"]
    for r, c, label in positions:
        binding = "&trans"
        if label == "ESC":
            binding = "&sys_reset"
        elif label == "DELETE":
            binding = "&uf2_boot"
        elif label.isdigit():
            binding = "&kp F" + str(10 if label == "0" else int(label))
        elif label == "MINUS":
            binding = "&kp F11"
        elif label == "EQUAL":
            binding = "&kp F12"
        out.append(f"                {binding} /* {r},{c}: {label} */")
    out += ["            >;", "        };", "    };", "};"]
    (ROOT / "include/tofu65_3_0-default-keymap.dtsi").write_text("\n".join(out) + "\n")
    print("Generated 69-position union: 67 ANSI positions plus 2 split-key positions.")


if __name__ == "__main__":
    generate()
